window.atcAciklama = function (kod) {
  kod = String(kod || "").toUpperCase().replace(/\s/g, "");
  if (!/^[A-Z]\d\d/.test(kod)) return null;
  const A = window.ATC;
  const ana = A[kod[0]];
  for (const n of [5, 4, 3]) { const k = kod.slice(0, n); if (kod.length >= n && A[k]) return { ana, detay: A[k] }; }
  return ana ? { ana, detay: null } : null;
};
